print("17 + 5 =", 17 + 5) # 22
print("17 - 5 =", 17 - 5) # 12
print("17 * 5 =", 17 * 5) # 85
print("17 / 5 =", 17 / 5) # 3.4
print("17 // 5 =", 17 // 5) # 3
print("17 % 5 =", 17 % 5) # 2
print("17 ** 5 =", 17 ** 5) # 1419857

print("-17 + 5 =", -17 + 5) # -12
print("-17 - 5 =", -17 - 5) # -22
print("-17 * 5 =", -17 * 5) # -85
print("-17 / 5 =", -17 / 5) # -3.4
print("-17 // 5 =", -17 // 5) # -4 rounded to -infinity
print("-17 % 5 =", -17 % 5) # 2 (wrong); 3 used as the remainder instead of 2 because it uses the floor of -4 to find the remainder
print("-17 ** 5 =", (-17) ** 5) # -1419857